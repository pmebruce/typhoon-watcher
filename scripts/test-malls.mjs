import assert from 'node:assert/strict';
import {MALLS,parseMall,getMalls,taiwanDay} from '../worker/malls.js';
const day='2026-10-24',mall=MALLS.find(x=>x.id==='zhubei');
const doc=body=>'<html><head><title>遠百竹北 颱風營業公告</title><meta property="article:published_time" content="2026-10-24T09:00:00+08:00"></head><article>'+body+'</article></html>';
assert.equal(parseMall(doc('遠百竹北今天正常營業。'),mall,day).state,'正常營業');
assert.equal(parseMall(doc('遠百竹北今天暫停營業。'),mall,day).kind,'closed');
assert.equal(parseMall(doc('遠百竹北今天延後至下午2時營業。'),mall,day).state,'14:00 開始營業');
assert.equal(parseMall(doc('遠百竹北明日暫停營業。'),mall,day),null);
assert.equal(parseMall(doc('遠百竹北10/23暫停營業。'),mall,day),null);
assert.equal(parseMall(doc('遠百竹北今天正常營業。').replaceAll('2026-10-24','2025-10-24'),mall,day),null);
assert.equal(parseMall(doc('遠百竹北部分專櫃暫停營業。'),mall,day),null);
assert.equal(parseMall(doc('遠百竹北今天正常營業。遠百竹北今天暫停營業。'),mall,day),null);
assert.equal(parseMall('<h1>遠百竹北營業時間</h1>11:00–22:00',mall,day),null);
assert.equal(taiwanDay(new Date('2026-10-24T16:01:00Z')),'2026-10-25');
const now=new Date('2026-10-24T06:00:00Z');
let calls=0;const broken=await getMalls(async()=>{calls++;throw Error('offline');},now);
assert.equal(broken.items.length,6);assert(broken.items.every(x=>!x.ok&&x.state==='本次無法確認'));assert.equal(calls,7);
const links=await getMalls(async url=>new Response(url.includes('/notice')?doc('遠百竹北今天停止營業。'):url.includes('/72/')?'<a href="/notice">颱風營業公告</a>':''),now);
assert.equal(links.items.find(x=>x.id==='zhubei').kind,'closed');
const news='<meta property="article:published_time" content="2026-10-24T11:00:00+08:00"><title>颱風營業安排</title><section class="article-content__editor"><p>竹北遠百、竹北享平方及新竹大遠百今天正常營業。</p><p>SOGO新竹店、iFG遠雄廣場新竹店今天延至下午2時開門。</p><p>巨城今天正常營業，巨城部分專櫃暫停營業。</p></section>';
const daily=await getMalls(async url=>new Response(url.includes('udn.com')?news:''),now);
assert(daily.items.every(x=>x.ok&&x.sourceType==='news'));
const next=await getMalls(async url=>new Response(url.includes('udn.com')?news:''),new Date('2026-10-25T01:00:00Z'));
assert(next.items.every(x=>!x.ok));
console.log('Date validity, future notices, partial closures, conflict, offline, discovery and media fallback checks passed.');
